#!/usr/bin/env python3
"""Offline Beta 2 content integrity gate. No emulator, network, or phone required.

This checks catalog source and original image provenance. Run after rendering
or importing art. A passing result does NOT constitute owner visual approval.
"""
from __future__ import annotations
import argparse
import hashlib
import json
import re
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
CATALOG = ROOT / "core/src/main/kotlin/com/playereden/sudokutogether/core/Cosmetics.kt"
MAPPING = ROOT / "app/src/main/java/com/playereden/sudokutogether/AnimalPortraits.kt"
MANIFEST = ROOT / "design/beta2-content-pack/ocean-woodland-eight-review/manifest.json"
DEST = ROOT / "app/src/main/res/drawable-nodpi"

def require(ok: bool, message: str) -> None:
    if not ok:
        raise SystemExit("FAIL: " + message)
    print("PASS:", message)

def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--require-original-art", action="store_true",
                        help="Release gate: require original PNG bytes, not vector reconstructions")
    args = parser.parse_args()
    catalog = CATALOG.read_text()
    mapping = MAPPING.read_text()
    data = json.loads(MANIFEST.read_text())
    items = data["items"]
    verified = []
    require(len(items) == 8, "exactly eight original art records")
    require(len({item["id"] for item in items}) == 8, "eight unique original asset IDs")
    for item in items:
        identifier = item["id"]
        require(re.fullmatch(r"(ocean|woodland)_[a-z_]+", identifier) is not None,
                f"{identifier}: safe resource identifier")
        require(identifier in catalog, f"{identifier}: catalog registration")
        require(f'"{identifier}" -> R.drawable.{identifier}' in mapping,
                f"{identifier}: Android drawable mapping")
        path = DEST / (identifier + ".png")
        if not path.exists():
            require(not args.require_original_art, f"{identifier}: original PNG present")
            print(f"PENDING {identifier}: generated by CI or not imported")
            continue
        with Image.open(path) as image:
            require(image.size == (512, 512) and image.mode == "RGBA",
                    f"{identifier}: 512x512 RGBA")
            lo, hi = image.getchannel("A").getextrema()
            require(lo == 0 and hi > 0, f"{identifier}: transparent nonempty sprite")
        actual = hashlib.sha256(path.read_bytes()).hexdigest()
        if args.require_original_art:
            require(actual == item["sha256"], f"{identifier}: EXACT original SHA-256")
        elif actual != item["sha256"]:
            print(f"REVIEW ONLY {identifier}: PNG differs from original approved-candidate hash")
        else:
            print(f"ORIGINAL {identifier}: SHA-256 matches source art")
        verified.append({"id": identifier, "sha256": actual, "bytes": path.stat().st_size,
                         "matches_original": actual == item["sha256"]})
    for family, expected in (("woodland", 17), ("ocean", 11),
                             ("garden", 9), ("farm", 6)):
        if family == "woodland":
            block = catalog.split("private val woodlandEntries =", 1)[1].split(
                "private val oceanEntries =", 1)[0]
            count = len(re.findall(r'"[a-z_]+" to \d+', block))
        else:
            block = catalog.split(f"private val {family}Entries =", 1)[1].split(
                "private val ", 1)[0]
            count = len(re.findall(r'CatalogEntry\("'+family+r'_', block))
        require(count == expected, f"{family}: {expected} stable portrait entries")
    receipt = ROOT / "build/beta2-unified75-original-art-manifest.json"
    receipt.parent.mkdir(parents=True, exist_ok=True)
    receipt.write_text(json.dumps({"required_original_art": args.require_original_art,
        "passed": len(verified) == 8 and all(x["matches_original"] for x in verified),
        "items": verified}, indent=2) + "\n", encoding="utf-8")
    print("PASS: catalog/art provenance checks complete")
    if not args.require_original_art:
        print("NOTE: normal mode is staging-only. Release requires --require-original-art and owner visual review.")

if __name__ == "__main__":
    main()
